#!/usr/bin/env python3
"""Stage 0 deliverable: freeze the Jain.bitR7 POWER SUMS q=0..45 as the moment oracle.

Computes S[q] = sum over (w, n_w) in bitR7 of n_w * w^q (exact integers) from the
platform-frozen Definitions/Def_IntMul_KappaJainData.lean, writes the JSON artifact
(~/bigo-campaign/stage0/bitR7_power_sums.json) and emits StaircasePort/MomOracle.lean
(kernel `decide` pins, big-literal pattern; no native_decide, no Rat).

Cross-checks built in: S0 == 1905413587 (childCount) and S1 == 57403754177 (rankSum),
both kernel-pinned in StaircasePort/D2Data.lean.
"""
import hashlib, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
JAIN = os.path.join(ROOT, 'Definitions', 'Def_IntMul_KappaJainData.lean')
STAGE0 = os.path.expanduser('~/bigo-campaign/stage0')
OUT_LEAN = os.path.join(ROOT, 'StaircasePort', 'MomOracle.lean')
QMAX = 45


def parse_bitr7():
    jain = open(JAIN).read()
    mb = re.search(r'def bitR7 : List \(ℕ × ℕ\) :=\s*\[(.*?)\]', jain, re.S)
    return sorted((int(a), int(b)) for a, b in re.findall(r'\((\d+),\s*(\d+)\)', mb.group(1)))


def main():
    hist = parse_bitr7()
    assert len(hist) == 37, 'bitR7 must have 37 entries, got %d' % len(hist)
    S = [sum(n * w ** q for w, n in hist) for q in range(QMAX + 1)]
    assert S[0] == 1905413587, S[0]
    assert S[1] == 57403754177, S[1]
    jsha = hashlib.sha256(open(JAIN, 'rb').read()).hexdigest()

    os.makedirs(STAGE0, exist_ok=True)
    art = dict(
        source='IntMul.Kappa.Jain.bitR7 (Definitions/Def_IntMul_KappaJainData.lean)',
        sha256_jaindata=jsha,
        definition='S[q] = sum over (w, n_w) in bitR7 of n_w * w^q (exact integers)',
        qmax=QMAX, m=529, W=108516254, entries=len(hist),
        S0_childCount=S[0], S1_rankSum=S[1],
        power_sums={str(q): str(s) for q, s in enumerate(S)})
    blob = json.dumps(art, indent=1, sort_keys=True) + '\n'
    for p in (os.path.join(STAGE0, 'bitR7_power_sums.json'),
              os.path.join(HERE, 'out', 'bitR7_power_sums.json')):
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, 'w').write(blob)
    print('artifact sha256 %s' % hashlib.sha256(blob.encode()).hexdigest())

    # ---- emit the Lean oracle (file header /- -/ BEFORE imports; maxRecDepth AFTER) ----
    pins = '\n'.join(
        '/-- S_%d = ∑ n_w·w^%d over `Jain.bitR7` — frozen (stage 0, sha256 %s…). -/\n'
        'theorem bitR7S%d : bitR7PowSum %d = %d := by decide'
        % (q, q, hashlib.sha256(blob.encode()).hexdigest()[:8], q, q, s)
        for q, s in enumerate(S))
    txt = '''/- Stage 0 frozen moment oracle: the power sums of the platform histogram
`IntMul.Kappa.Jain.bitR7`, q = 0..45 (37 distinct child widths — 46 sums over-pin the
multiset per Newton identities). Exact integers; generated by extract/gen_mom_oracle.py
from Definitions/Def_IntMul_KappaJainData.lean (sha256 5133d430…). These are the exact
quantities the r7 leaf must dominate: histMoment Jain.bitR7 529 τ = S_τ-as-real / 529^τ,
and multiset equality (pinned by S_0..S_45) gives moment equality at EVERY τ ∈ (0,1].
Built-in cross-check: S_0 = childCount 1905413587 and S_1 = rankSum 57403754177, both
kernel-pinned against the REGENERATED d2HIST in StaircasePort.D2Data (cross-tie file
MomOracleD2.lean, built explicitly — kept out of the root import so this oracle builds
on the Definitions closure alone, a host-pressure lesson from the stage-0 session). -/
import Definitions.Def_IntMul_KappaJainData

set_option autoImplicit false
set_option relaxedAutoImplicit false

namespace StaircasePort.Mom

set_option maxRecDepth 20000

/-- Power sum `S_q = ∑ n_w · w^q` of a child-width histogram `(w, n_w)` (exact, Nat). -/
def powSum (q : ℕ) (h : List (ℕ × ℕ)) : ℕ := (h.map (fun p => p.2 * p.1 ^ q)).sum

/-- The frozen oracle: power sum of the platform-frozen `Jain.bitR7`. -/
def bitR7PowSum (q : ℕ) : ℕ := powSum q IntMul.Kappa.Jain.bitR7

%s

end StaircasePort.Mom
''' % pins
    open(OUT_LEAN, 'w').write(txt)
    print('emitted %s (%d pins)' % (OUT_LEAN, QMAX + 1))


if __name__ == '__main__':
    main()
