#!/usr/bin/env python3
"""Generate StaircasePort/CertData.lean + StaircasePort/NEBlocks.lean from
extract/out/{cert_data,staircase_data}.json (exact ints only; no floating point anywhere).
Also sanity-checks the hu/hv/hT analogue values at the extracted witness and prints the
verdict (recorded in SCAFFOLD.md)."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
cert = json.load(open(os.path.join(HERE, 'out', 'cert_data.json')))
stair = json.load(open(os.path.join(HERE, 'out', 'staircase_data.json')))
T = json.load(open(os.path.join(HERE, 'out', 'T_data.json')))

def ilist(name, vals, ty='ℤ'):
    return 'def %s : List %s := [%s]' % (name, ty, ', '.join(str(v) for v in vals))

def llname(rows, per=9):
    out = []
    for r in rows:
        chunks = [', '.join(str(x) for x in r[i:i+per]) for i in range(0, len(r), per)]
        out.append('  [' + ', '.join(chunks) + ']')
    return '[\n' + ',\n'.join(out) + ']'

lab = cert['labels']; co = cert['coeffs']
# hu/hv/hT analogue sanity at the witness (Z values; nonzero over Z => nonzero over Q)
p, xi, v, nu = lab['x1'], lab['y1'], lab['x2'], lab['y2']
hu = p[0] * v[0] != 0
hv = xi[22] * nu[22] != 0
hT = all(p[l] * xi[22] + v[l] * nu[22] != 0 for l in range(1, 22))
print('witness hu=%s hv=%s hT(1..21)=%s' % (hu, hv, hT))

certdata = '''-- GENERATED by extract/gen_lean_data.py from extract/out/cert_data.json (exact ints).
-- Sources: check_stair.py design(23,'stair') + --ij witness (U = V = I + J, seed 1, first
-- sampled line pair), sparse_params(23, Random(1001)) lifted to [0,P); labels corrected by
-- extended-Euclid shifts of multiples of P so that y ⬝ x = 1 EXACTLY over Z (values mod P
-- unchanged). certP = 67108859 (check_stair.py:26). det(corner) != 0 mod certP: verified in
-- extract_cert.py; certRows·certCols = 1 mod certP verified (r6 certChk convention,
-- nb_flagBasis_solution.lean:57-59).

import Definitions.Def_IntMul_Kappa_R6_Defs4

namespace StaircasePort.Stair

open IntMul.Kappa.R6.Bit.NB

/-- The certificate prime (check_stair.py:26: "the prime of round six's draws"). -/
abbrev stairCertP : ℕ := %d

instance : Fact (1 < stairCertP) := ⟨by norm_num⟩

/-! ## N3 witness labels: x₁=p, y₁=ξ, x₂=v, y₂=ν (check_stair corner_at docstring :139:
q1 = I − p ξᵀ, q2 = I − v νᵀ ↔ Defs4 (1 − vecMulVec x₁ y₁) ⊗ₖ (1 − vecMulVec x₂ y₂)).
y ⬝ x = 1 exactly over Z (extract_cert.py fix_dot). -/

%s

%s

%s

%s

/-- ℚ versions (Fin-indexed, mirroring qx1..qy2, Defs4:1116-1119). -/
def stairQX1 : Fin 23 → ℚ := fun i => (stairWX1L.getD i 0 : ℚ)
def stairQY1 : Fin 23 → ℚ := fun i => (stairWY1L.getD i 0 : ℚ)
def stairQX2 : Fin 23 → ℚ := fun i => (stairWX2L.getD i 0 : ℚ)
def stairQY2 : Fin 23 → ℚ := fun i => (stairWY2L.getD i 0 : ℚ)

/-- ℕ-indexed ℚ accessors for the N4 nonvanishing statements. -/
def stairX1 (i : ℕ) : ℚ := (stairWX1L.getD i 0 : ℚ)
def stairY1 (i : ℕ) : ℚ := (stairWY1L.getD i 0 : ℚ)
def stairX2 (i : ℕ) : ℚ := (stairWX2L.getD i 0 : ℚ)
def stairY2 (i : ℕ) : ℚ := (stairWY2L.getD i 0 : ℚ)

/-! ## Staircase flag-family coefficients (check_stair.py:93-95 sparse_params, seed 1001,
lifted to [0,P); rows :164 λ_{h−1} = al·E(h−1,0) + be·E(0,h−1); cols :165 μ_j = a_j·E(j,j+1)
+ b_j·E(j+1,j)). -/

def stairAlZ : ℤ := %d
def stairBeZ : ℤ := %d

%s

%s

/-! ## Kernel certificate data (r6 certChk convention, Defs4:1000; rows·cols = 1 mod
stairCertP; rows = staircase corner mod stairCertP). -/

def stairCertRows : List (List ℕ) :=
%s

def stairCertCols : List (List ℕ) :=
%s

end StaircasePort.Stair
''' % (cert['certP'],
       ilist('stairWX1L', lab['x1']), ilist('stairWY1L', lab['y1']),
       ilist('stairWX2L', lab['x2']), ilist('stairWY2L', lab['y2']),
       co['al'], co['be'],
       ilist('stairAZL', co['a']), ilist('stairBZL', co['b']),
       llname(cert['certRows']), llname(cert['certCols']))

with open(os.path.join(ROOT, 'StaircasePort', 'CertData.lean'), 'w') as fh:
    fh.write(certdata)

blocks = stair['ne_blocks']
tups = ', '.join('(%d, %d, %d, %d)' % (b['i'], b['j'], b['rho'], b['cut']) for b in blocks)
nebl = '''-- GENERATED by extract/gen_lean_data.py from extract/out/staircase_data.json (exact ints).
-- The %d nontrivial NE blocks of the 45x45 staircase corner: (i, j, rho, cut) with
-- rho = evaluated rank profile rk(rows<=i, cols>=j) at the witness (check_stair.py:176) and
-- cut = the max-flow min vertex-cut bound of the rows-terms-cols graph (check_stair.py:57-90),
-- re-verified cut >= rho for every block (check_stair.py:178-183; extract run: all_ok=%s).

import Definitions.Def_IntMul_Kappa_R6_Defs4

namespace StaircasePort.Stair

/-- (i, j, rho_ij, cut_ij) for every nontrivial NE block; trivial blocks (rho = min(i+1, 45-j))
are omitted (check_stair.py:180). -/
def stairNEBlocks : List (ℕ × ℕ × ℕ × ℕ) := [%s]

theorem stairNEBlocks_length : stairNEBlocks.length = %d := rfl

theorem stairNEBlocks_cut_ge_rho :
    (stairNEBlocks.all fun t => decide (t.2.2.1 ≥ t.2.2.2)) = true := by native_decide

end StaircasePort.Stair
''' % (len(blocks), stair['ne_blocks_all_ok'], tups, len(blocks))
with open(os.path.join(ROOT, 'StaircasePort', 'NEBlocks.lean'), 'w') as fh:
    fh.write(nebl)
print('generated CertData.lean (%d B) + NEBlocks.lean (%d blocks)'
      % (len(certdata), len(blocks)))
