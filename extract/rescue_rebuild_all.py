#!/usr/bin/env python3
"""Rebuild the N2b extraction outputs after the 2026-11-06 workspace wipe.

Regenerates, deterministically, from vendored_check_stair_core.py + the SCAFFOLD-documented
pivot pattern (runs+offsets [(0,44,1),(1,23,21),(22,22,1),(23,21,1),(24,20,1),(25,2,18),
(43,1,1),(44,0,1)]):
  - pc (45 rightmost-pivot columns), rho profile, the 689 nontrivial NE blocks (i,j,rho,cut)
  - per-block cut SETS (R0,T0,C0) + term supports sr/sc via cut_bound_sets
  - out/ne_cuts.json
  - out/NEBlocks.lean  (full file: original value-pin section byte-shaped as the lost
    generated original + the N2b cut-SET sections with getD-based bulk decide pins)
Cross-checks (hard asserts): 689 blocks; cut >= rho everywhere with above==0 (cut==rho);
spot tuples (1,24,1,1),(2,24,2,2),(20,24,20,20),(25,3,25,25),(41,19,25,25); T0 ⊆ {23,46}
with 46 always in T0; |R0|+|T0|+|C0| == cut; sr/sc derived-from-cells == structure() terms.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from vendored_check_stair_core import design, structure, cut_bound, cut_bound_sets

H = 23
N = 2 * H - 1  # 45

def build_pc():
    pc = [-1] * N
    for (i0, j0, ln) in [(0, 44, 1), (1, 23, 21), (22, 22, 1), (23, 21, 1),
                         (24, 20, 1), (25, 2, 18), (43, 1, 1), (44, 0, 1)]:
        for k in range(ln):
            pc[i0 + k] = j0 + k
    assert -1 not in pc, pc
    return pc

def main():
    pc = build_pc()
    rho = [[sum(1 for r in range(i + 1) if pc[r] >= j) for j in range(N)] for i in range(N)]
    RC, CC = design(H, 'stair')
    rows_, cols_, terms = structure(H, RC, CC)

    blocks = []
    for i in range(N):
        for j in range(N):
            if rho[i][j] == min(i + 1, N - j):
                continue
            flow, R0, T0, C0 = cut_bound_sets(set(range(i + 1)), set(range(j, N)), terms)
            ref = cut_bound(set(range(i + 1)), set(range(j, N)), terms)
            assert flow == ref == rho[i][j], (i, j, flow, ref, rho[i][j])
            assert len(R0) + len(T0) + len(C0) == flow
            assert 46 in T0 and set(T0) <= {23, 46}, (i, j, T0)
            blocks.append(dict(i=i, j=j, rho=rho[i][j], cut=flow, R0=R0, T0=T0, C0=C0))

    assert len(blocks) == 689, len(blocks)
    spot = {(1, 24): (1, 1), (2, 24): (2, 2), (20, 24): (20, 20), (25, 3): (25, 25), (41, 19): (25, 25)}
    bmap = {(b['i'], b['j']): (b['rho'], b['cut']) for b in blocks}
    for k, v in spot.items():
        assert bmap[k] == v, (k, bmap[k], v)
    print('689/689 blocks rebuilt; cut==rho everywhere (above=0); spot tuples OK; T0 ⊆ {23,46}, 46∈T0 always')

    sr_derived, sc_derived = [], []
    for l in range(H):
        sr_derived.append({i for i, f in enumerate(rows_) if any(c[1] == l for c in f)})
        sc_derived.append({j for j, g in enumerate(cols_) if any(c[1] == l for c in g)})
    for k in range(H):
        sr_derived.append({i for i, f in enumerate(rows_) if any(c[0] == k for c in f)})
        sc_derived.append({j for j, g in enumerate(cols_) if any(c[0] == k for c in g)})
    sr_derived.append(set(range(N))); sc_derived.append(set(range(N)))
    assert all(sr_derived[t] == terms[t][0] and sc_derived[t] == terms[t][1] for t in range(47))
    SR = [sorted(s) for s in sr_derived]; SC = [sorted(s) for s in sc_derived]
    print('sr/sc derived-from-cells == structure() terms: True')

    os.makedirs(os.path.join(HERE, 'out'), exist_ok=True)
    with open(os.path.join(HERE, 'out', 'ne_cuts.json'), 'w') as f:
        json.dump(dict(h=H, n=N, pc=pc, terms=[[sorted(a), sorted(b)] for a, b in terms], blocks=blocks), f)
    print('wrote out/ne_cuts.json')
    write_neblocks(blocks, SR, SC)

def fmt_ll(ll):
    return '[' + ', '.join('[' + ', '.join(map(str, l)) + ']' for l in ll) + ']'

