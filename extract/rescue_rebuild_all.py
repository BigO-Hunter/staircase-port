    a.append('-- rho = evaluated rank profile rk(rows<=i, cols>=j) at the witness (check_stair.py:176) and')
    a.append('-- cut = the max-flow min vertex-cut bound of the rows-terms-cols graph (check_stair.py:57-90),')
    a.append('-- re-verified cut >= rho for every block (check_stair.py:178-183; rebuild run: all_ok=True).')
    a.append('')
