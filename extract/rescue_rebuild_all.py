    a.append('are omitted (check_stair.py:180). -/')
    tuples = ', '.join('(%d, %d, %d, %d)' % (b['i'], b['j'], b['rho'], b['cut']) for b in blocks)
    a.append('def stairNEBlocks : List (ℕ × ℕ × ℕ × ℕ) := [' + tuples + ']')
    a.append('')
    a.append('theorem stairNEBlocks_length : stairNEBlocks.length = 689 := rfl')
